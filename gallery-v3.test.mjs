import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';
import { validateScriptUrl, googleFrameOrigin } from './gallery-drive-v3.js';

assert.equal(validateScriptUrl('https://script.google.com/macros/s/deploy_123/exec'),'https://script.google.com/macros/s/deploy_123/exec');
for (const value of [null,'http://script.google.com/macros/s/x/exec','https://example.com/macros/s/x/exec','https://script.google.com/macros/s/x/dev','https://script.google.com/macros/s/x/exec?token=secret']) assert.equal(validateScriptUrl(value),null);
assert.equal(googleFrameOrigin('https://abc-123.googleusercontent.com'),true);
assert.equal(googleFrameOrigin('https://googleusercontent.com.attacker.test'),false);
const source = await readFile(new URL('./gallery-v3.js',import.meta.url),'utf8');
const functions = source.slice(source.indexOf('export function uploadMime')).replaceAll('export function ','function ');
const context = vm.createContext({});
vm.runInContext(functions+';this.policy={uploadMime,isAcceptedPhoto,uploadErrorKey}',context);
const {uploadMime,isAcceptedPhoto,uploadErrorKey}=context.policy;
assert.equal(uploadMime({name:'IMG.HEIC',type:''}),'image/heic');
assert.equal(isAcceptedPhoto({name:'IMG.HEIC',type:''}),true);
assert.equal(isAcceptedPhoto({name:'photo.svg',type:'image/svg+xml'}),false);
assert.equal(uploadErrorKey({code:'DRIVE_QUOTA'}),'quota');
assert.equal(uploadErrorKey({code:'IMAGE_DECODE'}),'decode');
assert.equal(uploadErrorKey({code:'TIMEOUT'}),'network');
assert.equal(uploadErrorKey({code:'RATE_LIMIT'}),'rate');
assert.equal(uploadErrorKey({code:'internal private error'}),'failed');
console.log('PASS: Apps Script URL/origin boundaries, HEIC recognition and localized quota/errors.');
